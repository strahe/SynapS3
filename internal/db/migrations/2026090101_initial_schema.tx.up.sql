CREATE TABLE tasks (
  id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  type text NOT NULL,
  input_version integer NOT NULL,
  subject_type text NOT NULL,
  subject_key text NOT NULL,
  generation bigint,
  retry_of_task_id bigint,
  input_json jsonb NOT NULL,
  checkpoint_json jsonb,
  runtime_json jsonb NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  resume_mode text NOT NULL DEFAULT 'execute',
  available_at timestamptz NOT NULL,
  wait_reason text,
  retry_count integer NOT NULL DEFAULT 0,
  failure_reason text,
  last_error text,
  status_message text,
  claim_generation bigint NOT NULL DEFAULT 0,
  lease_until timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  work_started_at timestamptz,
  acknowledged_at timestamptz,
  superseded_at timestamptz,
  CONSTRAINT chk_tasks_identity CHECK (type <> '' AND subject_type <> '' AND subject_key <> '' AND (generation IS NULL OR generation >= 0) AND input_version >= 1),
  CONSTRAINT chk_tasks_resume_mode CHECK (resume_mode IN ('execute','recover')),
  CONSTRAINT chk_tasks_reason_codes CHECK ((wait_reason IS NULL OR wait_reason <> '') AND (failure_reason IS NULL OR failure_reason <> '')),
  CONSTRAINT chk_tasks_retry CHECK (retry_count >= 0),
  CONSTRAINT chk_tasks_generation CHECK (claim_generation >= 0),
  CONSTRAINT chk_tasks_retry_parent CHECK (retry_of_task_id IS NULL OR retry_of_task_id < id),
  CONSTRAINT chk_tasks_status CHECK (status IN ('pending','running','failed','completed','cancelled')),
  CONSTRAINT chk_tasks_claim CHECK ((status = 'running' AND lease_until IS NOT NULL AND claim_generation > 0) OR (status <> 'running' AND lease_until IS NULL)),
  CONSTRAINT chk_tasks_finished CHECK ((status IN ('failed','completed','cancelled')) = (finished_at IS NOT NULL)),
  CONSTRAINT chk_tasks_acknowledged CHECK (acknowledged_at IS NULL OR status = 'failed'),
  CONSTRAINT chk_tasks_superseded CHECK (superseded_at IS NULL OR status IN ('failed','completed','cancelled')),
  CONSTRAINT chk_tasks_input_json_json CHECK (jsonb_typeof(input_json) = 'object'),
  CONSTRAINT chk_tasks_checkpoint_json_json CHECK (checkpoint_json IS NULL OR jsonb_typeof(checkpoint_json) = 'object'),
  CONSTRAINT chk_tasks_runtime_json_json CHECK (jsonb_typeof(runtime_json) = 'object'),
  PRIMARY KEY (id),
  FOREIGN KEY (retry_of_task_id) REFERENCES tasks (id) ON UPDATE RESTRICT ON DELETE RESTRICT
);
-- A superseded round leaves its identity to the retry that replaces it. A NULL
-- generation never conflicts, so such tasks are not deduplicated.
CREATE UNIQUE INDEX uq_tasks_identity ON tasks (type, subject_type, subject_key, generation) WHERE (superseded_at IS NULL);
CREATE UNIQUE INDEX uq_tasks_retry_parent ON tasks (retry_of_task_id) WHERE (retry_of_task_id IS NOT NULL);
CREATE INDEX idx_tasks_type_id ON tasks (type, id);
CREATE INDEX idx_tasks_subject ON tasks (subject_type, subject_key, id);
CREATE INDEX idx_tasks_status_id ON tasks (status, id) WHERE (status <> 'completed');
-- Same condition as live_tasks, so queries on the view can use it.
CREATE INDEX idx_tasks_live ON tasks (id) WHERE (status IN ('pending','running','failed') AND acknowledged_at IS NULL AND superseded_at IS NULL);
CREATE INDEX idx_tasks_pending ON tasks (available_at, id) WHERE (status = 'pending');
CREATE INDEX idx_tasks_recovery ON tasks (lease_until, id) WHERE (status = 'running');
CREATE INDEX idx_tasks_pending_type_available ON tasks (type, available_at, id) WHERE (status = 'pending');
CREATE INDEX idx_tasks_recovery_type_lease ON tasks (type, lease_until, id) WHERE (status = 'running');
-- superseded_at is NULL in every entry; ordering by it keeps the planner on
-- this index when it misjudges how few failures are still current.
CREATE INDEX idx_tasks_current_failed ON tasks (subject_type, subject_key, superseded_at, id) WHERE (status = 'failed' AND superseded_at IS NULL);
