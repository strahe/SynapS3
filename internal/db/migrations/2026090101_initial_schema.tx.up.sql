  CONSTRAINT chk_storage_commit_requests_counts CHECK (piece_count >= 0 AND sends >= 0 AND refusals >= 0),
  CONSTRAINT chk_storage_commit_requests_seal_intent CHECK (seal_requested_at IS NULL OR status = 'collecting'),
  CONSTRAINT chk_storage_commit_requests_task CHECK ((status IN ('confirmed', 'abandoned')) = (task_id IS NULL)),
  CONSTRAINT chk_storage_commit_requests_shape CHECK ( (status = 'collecting' AND piece_count = 0 AND extra_data_hex IS NULL AND sealed_at IS NULL AND first_sent_at IS NULL AND sends = 0 AND submitted_at IS NULL AND last_sent_at IS NULL AND tx_hash IS NULL AND first_piece_id IS NULL AND confirmed_tx_hash IS NULL AND confirmed_at IS NULL) OR (status = 'ready' AND piece_count >= 1 AND extra_data_hex IS NOT NULL AND sealed_at IS NOT NULL AND sends = 0 AND submitted_at IS NULL AND tx_hash IS NULL AND first_piece_id IS NULL AND confirmed_tx_hash IS NULL AND confirmed_at IS NULL) OR (status = 'submitted' AND piece_count >= 1 AND extra_data_hex IS NOT NULL AND sealed_at IS NOT NULL AND first_sent_at IS NOT NULL AND sends >= 1 AND submitted_at IS NOT NULL AND last_sent_at IS NOT NULL AND first_piece_id IS NULL AND confirmed_tx_hash IS NULL AND confirmed_at IS NULL) OR (status = 'confirmed' AND piece_count >= 1 AND extra_data_hex IS NOT NULL AND sealed_at IS NOT NULL AND first_sent_at IS NOT NULL AND first_piece_id IS NOT NULL AND confirmed_at IS NOT NULL AND (confirmed_tx_hash IS NULL OR tx_hash IS NOT NULL)) OR (status = 'abandoned' AND last_error IS NOT NULL AND first_piece_id IS NULL AND confirmed_tx_hash IS NULL AND confirmed_at IS NULL) ),
